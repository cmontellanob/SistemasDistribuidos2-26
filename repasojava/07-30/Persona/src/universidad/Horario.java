package universidad;

/**
 *
 * @author Dell
 */
public class Horario {
    
    Dia dia;
    String hora;
    Aula aula;

    public Horario(Dia dia, String hora, Aula aula) {
        this.dia = dia;
        this.hora = hora;
        this.aula = aula;
    }

    public Dia getDia() {
        return dia;
    }

    public void setDia(Dia dia) {
        this.dia = dia;
    }

    public String getHora() {
        return hora;
    }

    public void setHora(String hora) {
        this.hora = hora;
    }

    public Aula getAula() {
        return aula;
    }

    public void setAula(Aula aula) {
        this.aula = aula;
    }
    
}
